#!/usr/bin/env python3
"""Build vendor/pdf-fonts.js: static TrueType instances of the bundled variable fonts,
used by "Scarica PDF" (assets/js/05c-pdf.js) to embed real, selectable text in the PDF.

Source: assets/fonts/*.woff2 (Inter and JetBrains Mono, SIL Open Font License 1.1, see
assets/fonts/LICENSE-*-OFL.txt). For every weight listed below the script
  1. instantiates the latin, latin-ext and greek variable subsets at that weight,
  2. merges the three static fonts into one (glyph names are shared by the subsets),
  3. drops layout/hinting/variation tables (the PDF writer positions every glyph
     from the browser layout, so GSUB/GPOS are not needed) and subsets to the
     union of the three unicode ranges,
  4. stores the TTF zlib-compressed (deflate = PDF FlateDecode) and base64 encoded.
The JS file defines window.DM_PDF_FONTS = {licence, fonts:{'sans-400': {b64, len}, ...}}.

Usage (reproducible, needs fonttools + brotli):
  pip install fonttools brotli
  python3 docmapv1/tools/make_pdf_fonts.py
"""
import base64, io, json, os, zlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, 'assets', 'fonts')
OUT = os.path.join(ROOT, 'vendor', 'pdf-fonts.js')
# Weights: measured from the computed styles of every preset x content mode x template (v9):
# Inter 400/500/600/700/800, JetBrains Mono 400/700/800. Inter 900 and Mono 500/600 are kept as
# headroom for new templates; 05c-pdf.js maps any other weight to the nearest instance.
FAMILIES = {
  'sans': ('inter', 'Inter', [400, 500, 600, 700, 800, 900]),
  'mono': ('jetbrains-mono', 'JetBrains Mono', [400, 500, 600, 700, 800]),
}
SUBSETS = ['latin', 'latin-ext', 'greek']


def static_instance(path, wght):
  f = TTFont(path)
  f.flavor = None   # write plain TrueType, not WOFF2
  lo, hi = f['fvar'].axes[0].minValue, f['fvar'].axes[0].maxValue
  return instancer.instantiateVariableFont(f, {'wght': max(lo, min(hi, wght))})


def merge(fonts):
  base = fonts[0]
  order = list(base.getGlyphOrder())
  have = set(order)
  glyf, hmtx = base['glyf'], base['hmtx']
  cmap = dict(base.getBestCmap())
  for f in fonts[1:]:
    for name in f.getGlyphOrder():
      if name in have:
        continue
      have.add(name)
      order.append(name)
      glyf.glyphs[name] = f['glyf'][name]
      hmtx.metrics[name] = f['hmtx'].metrics[name]
    for cp, name in f.getBestCmap().items():
      cmap.setdefault(cp, name)
  base.setGlyphOrder(order)
  glyf.glyphOrder = order
  for t in base['cmap'].tables:
    if t.isUnicode():
      t.cmap = {cp: n for cp, n in cmap.items() if t.format == 12 or cp <= 0xFFFF}
  base['maxp'].numGlyphs = len(order)
  buf = io.BytesIO()
  base.save(buf)
  buf.seek(0)
  return TTFont(buf), set(cmap)


def build(prefix, wght):
  fonts = [static_instance(os.path.join(FONTS, '%s-%s-wght-normal.woff2' % (prefix, s)), wght) for s in SUBSETS]
  font, cps = merge(fonts)
  opt = subset.Options()
  opt.layout_features = []
  opt.hinting = False
  opt.notdef_outline = True
  opt.glyph_names = False
  opt.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]   # keep copyright + licence (OFL)
  opt.drop_tables += ['GSUB', 'GPOS', 'GDEF', 'STAT', 'gasp', 'prep', 'DSIG', 'MVAR', 'HVAR', 'avar', 'fvar', 'gvar']
  sub = subset.Subsetter(opt)
  sub.populate(unicodes=sorted(cps))
  sub.subset(font)
  font.flavor = None
  buf = io.BytesIO()
  font.save(buf)
  return buf.getvalue()


def main():
  out = {}
  total = 0
  for fam, (prefix, label, weights) in FAMILIES.items():
    for w in weights:
      ttf = build(prefix, w)
      z = zlib.compress(ttf, 9)
      out['%s-%d' % (fam, w)] = {'len': len(ttf), 'b64': base64.b64encode(z).decode('ascii')}
      total += len(z)
      print('%s-%d: ttf %d bytes, deflate %d' % (fam, w, len(ttf), len(z)))
  js = ('/* DocMap 2026 - static TrueType instances of Inter and JetBrains Mono for "Scarica PDF".\n'
        '   Generated by tools/make_pdf_fonts.py from assets/fonts/*.woff2 - do not edit by hand.\n'
        '   Inter: Copyright (c) 2016 The Inter Project Authors. JetBrains Mono: Copyright 2020\n'
        '   The JetBrains Mono Project Authors. Both licensed under the SIL Open Font License 1.1,\n'
        '   see assets/fonts/LICENSE-Inter-OFL.txt and assets/fonts/LICENSE-JetBrainsMono-OFL.txt.\n'
        '   Each entry: zlib-deflated TrueType (b64) + uncompressed length. */\n'
        'window.DM_PDF_FONTS = ' + json.dumps({'fonts': out}, separators=(',', ':')) + ';\n')
  with open(OUT, 'w', encoding='ascii') as f:
    f.write(js)
  print('wrote %s (%d bytes, fonts %d bytes deflated)' % (OUT, len(js), total))


if __name__ == '__main__':
  main()
