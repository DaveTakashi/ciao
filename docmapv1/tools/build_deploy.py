#!/usr/bin/env python3
"""DocMap 2026 — build the static web deploy (v10).

Copies the app (no tests, tools, docs) into a target folder and adds what a static host needs:
  docmap.config.js (mode 'web', frozen) · .htaccess (Apache rewrite /<base>/q/<code> → scan.html + security headers)
  404.html (redirects /q/<code> to scan.html?q=<code> on hosts without rewrites) · robots.txt (Disallow: /)
  nginx-docmap.conf.example · README-DEPLOY.md (Italian upload steps) · DEPLOY-MANIFEST.txt (sha256 of every file)

Deterministic (sorted, no timestamps), never deletes anything: files are written / overwritten in place.
Usage:
  python3 docmapv1/tools/build_deploy.py [TARGET] [--base-path /studio-de/] [--slug studio-de]
                                         [--domain https://docmap.pr-it.it] [--studio-name "Studio …"]
Default TARGET: <folder containing docmapv1>/deploy/<slug>
"""
import argparse, hashlib, json, os, re, shutil, sys

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COPY_FILES = ['index.html', 'scan.html']
COPY_DIRS = ['assets', 'vendor']
SKIP = re.compile(r'(^|/)(\.DS_Store|Thumbs\.db|\.git.*)$')


def norm_base(b):
    b = '/' + b.strip().strip('/') + '/'
    return '/' if b == '//' else b


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def config_js(a):
    cfg = {'mode': 'web', 'basePath': a.base_path, 'apiBase': None, 'studioSlug': a.slug, 'studioName': a.studio_name}
    return ('/* DocMap 2026 — web deploy configuration, generated by tools/build_deploy.py (do not edit by hand:\n'
            '   rebuild instead). mode "web": login required on every page, data encrypted in each browser. */\n'
            'window.DOCMAP_CONFIG = Object.freeze(' + json.dumps(cfg, ensure_ascii=False, indent=2) + ');\n')


CSP = ("default-src 'self'; script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; "
       "img-src 'self' data: blob:; font-src 'self'; connect-src 'self'; worker-src 'self' blob:; object-src 'none'; "
       "base-uri 'self'; frame-ancestors 'none'; form-action 'self'")


def htaccess(a):
    b = a.base_path
    return f"""# DocMap 2026 — Apache configuration (mod_rewrite, mod_headers). Generated by tools/build_deploy.py
# The server holds ONLY the program: no data is ever uploaded here (see docs/SICUREZZA.md).
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 {b}404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase {b}
  # Force HTTPS (uncomment if the host does not already do it; behind a proxy use X-Forwarded-Proto instead)
  # RewriteCond %{{HTTPS}} !=on
  # RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]
  # QR path routing: {b}q/<short_code> is served by scan.html (the URL stays the same)
  RewriteRule ^q/([A-Za-z0-9_-]{{1,40}})/?$ scan.html [L,QSA]
  # the browser's preload scanner may ask for q/assets/… before scan.html sets <base>: serve the real files
  RewriteRule ^q/((assets|vendor)/.+|docmap\\.config\\.js)$ $1 [L]
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "no-referrer"
  Header always set X-Frame-Options "DENY"
  Header always set X-Robots-Tag "noindex, nofollow"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()"
  Header always set Strict-Transport-Security "max-age=31536000"
  Header always set Content-Security-Policy "{CSP}"
  <FilesMatch "\\.(html|js|css)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType application/javascript .js
  AddType font/woff2 .woff2
</IfModule>
"""


def nginx(a):
    b = a.base_path
    return f"""# DocMap 2026 — nginx snippet (inside the server {{ }} block of {a.domain}). Generated by tools/build_deploy.py
location {b} {{
    alias /var/www/docmap{b};          # folder where the deploy was uploaded
    index index.html;
    try_files $uri $uri/ =404;
    error_page 404 {b}404.html;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "no-referrer" always;
    add_header X-Frame-Options "DENY" always;
    add_header X-Robots-Tag "noindex, nofollow" always;
    add_header Strict-Transport-Security "max-age=31536000" always;
    add_header Content-Security-Policy "{CSP}" always;
}}
# QR path routing: {b}q/<short_code> → scan.html (internal, the URL stays the same)
location ~ ^{re.escape(b)}q/[A-Za-z0-9_-]{{1,40}}/?$ {{
    default_type text/html;
    alias /var/www/docmap{b}scan.html;
}}
location ~ ^{re.escape(b)}q/((assets|vendor)/.+|docmap\\.config\\.js)$ {{
    alias /var/www/docmap{b}$1;      # preload requests made before <base> applies
}}
"""


def page_404(a):
    b = a.base_path
    return f"""<!DOCTYPE html>
<html lang="it"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow"><title>DocMap</title>
<style>body{{font-family:system-ui,sans-serif;background:#F1F5F9;color:#0F172A;display:grid;place-items:center;min-height:100vh;margin:0;padding:16px}}
div{{background:#fff;border:1px solid #E2E8F0;border-radius:16px;padding:24px;max-width:420px}}a{{color:#2563EB;font-weight:700}}</style>
<script>
  /* Hosts without rewrites serve this page for {b}q/<short_code>: send the visitor to scan.html?q=<short_code>. */
  (function(){{
    var m = location.pathname.match(/\\/q\\/([A-Za-z0-9_-]{{1,40}})\\/?$/);
    if (m) location.replace({json.dumps(b)} + 'scan.html?q=' + m[1] + location.hash);
  }})();
</script></head>
<body><div><h1>Pagina non trovata</h1><p>Questa pagina non esiste. / This page does not exist.</p><p><a href="{b}index.html">DocMap</a></p></div></body></html>
"""


def readme(a):
    b, d = a.base_path, a.domain.rstrip('/')
    return f"""# DocMap — pubblicazione web ({d}{b})

Questa cartella contiene **solo il programma**: nessun dato dello studio. I dati restano in ogni browser,
cifrati (AES-256-GCM, chiave ricavata dalla password con PBKDF2), e si caricano con il pacchetto di
sincronizzazione esportato da DocMap sul PC ("Copia export per web app" → "Importa dati da client locale").

## Caricamento (hosting Apache, es. cPanel / FTP)

1. Carica **tutto il contenuto** di questa cartella in `{b}` sul dominio `{d}` (anche i file nascosti
   `.htaccess`: nel client FTP attiva "mostra file nascosti").
2. Verifica che il sito sia raggiungibile solo in **HTTPS** (certificato attivo). Se l'hosting non forza HTTPS,
   togli il `#` dalle due righe "Force HTTPS" in `.htaccess`.
3. Apri `{d}{b}` → al primo accesso **ogni dispositivo** crea il proprio amministratore (nome utente + PIN o
   password). Poi importa i dati dal pacchetto di sincronizzazione.
4. Prova un QR: `{d}{b}q/dm26XXXXXXXX` deve aprire la scheda del faldone (dopo il login).
   Se vedi "Pagina non trovata", l'hosting non applica `.htaccess`: va bene lo stesso, `404.html` reindirizza
   a `scan.html?q=…`; altrimenti usa lo snippet `nginx-docmap.conf.example`.
5. In DocMap sul PC, **Impostazioni › Destinazione finale** deve essere `{d}{b}q/{{short_code}}` e il manifest
   qr7.it va riesportato e caricato se avevi una destinazione diversa.

## Aggiornare

Rigenera la cartella con `python3 docmapv1/tools/build_deploy.py` e ricarica tutti i file (sovrascrivi).
Il programma non cancella nulla: se un file è stato tolto da una versione nuova, eliminalo a mano dal server.
Controlla `DEPLOY-MANIFEST.txt` (impronte sha256) per verificare che il caricamento sia completo.

## Cosa NON fa ancora (serve il back-end Python)

- Niente sincronizzazione automatica tra dispositivi: ogni browser ha la sua copia, aggiornata con i pacchetti.
- Gli utenti e i PIN valgono solo nel browser dove sono stati creati; non si può revocare un utente da remoto.
- Se si perde il PIN di tutti gli amministratori di un dispositivo, i dati di quel browser non si recuperano
  (si reimportano dal pacchetto).
Dettagli: `docs/SICUREZZA.md` e `docs/API-CONTRACT.md` nello zip del progetto.
"""


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 16), b''):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description='Build the DocMap static web deploy')
    ap.add_argument('target', nargs='?')
    ap.add_argument('--base-path', default='/studio-de/')
    ap.add_argument('--slug', default='studio-de')
    ap.add_argument('--domain', default='https://docmap.pr-it.it')
    ap.add_argument('--studio-name', default='')
    a = ap.parse_args()
    a.base_path = norm_base(a.base_path)
    if not re.fullmatch(r'[a-z0-9-]{1,40}', a.slug):
        sys.exit('slug: lowercase letters, digits and dashes only')
    target = os.path.abspath(a.target or os.path.join(os.path.dirname(APP), 'deploy', a.slug))
    if os.path.commonpath([target, APP]) == APP and not target.startswith(os.path.join(APP, 'tests')):
        sys.exit('target must be outside docmapv1/ (or under docmapv1/tests/ for the test suite)')
    files = []
    for name in COPY_FILES:
        files.append(name)
    for d in COPY_DIRS:
        for root, dirs, names in os.walk(os.path.join(APP, d)):
            dirs.sort()
            for n in sorted(names):
                rel = os.path.relpath(os.path.join(root, n), APP).replace(os.sep, '/')
                if not SKIP.search(rel):
                    files.append(rel)
    for rel in files:
        dst = os.path.join(target, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(APP, rel), dst)
    gen = {'docmap.config.js': config_js(a), '.htaccess': htaccess(a), '404.html': page_404(a), 'robots.txt': 'User-agent: *\nDisallow: /\n',
           'nginx-docmap.conf.example': nginx(a), 'README-DEPLOY.md': readme(a)}
    for rel in sorted(gen):
        write(os.path.join(target, rel), gen[rel])
    allf = sorted(files + list(gen))
    write(os.path.join(target, 'DEPLOY-MANIFEST.txt'), ''.join(f'{sha(os.path.join(target, r))}  {r}\n' for r in allf))
    print(f'DocMap deploy: {len(allf) + 1} files → {target} (base path {a.base_path})')


if __name__ == '__main__':
    main()
