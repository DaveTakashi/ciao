"""`python -m docmap_server setup …` — the command-line twin of server-php/setup.php.

Creates the data folder (with the same defensive .htaccess / index.html), a random AES-256 key and one access token per
person, writes the configuration (config.json by default, or config.php in setup.php's exact format with --format php)
and prints each token ONCE (the file keeps only their SHA-256). Refuses to run when the configuration file exists.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import re
import sys
import time

from .api import valid_user_name


def _php_export(v, indent=""):
    """var_export() of the config array (same layout setup.php writes)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "NULL"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"
    items = list(v.items()) if isinstance(v, dict) else list(enumerate(v))
    out = "\n" + indent + "array (\n"
    for k, x in items:
        out += indent + "  " + (str(k) if isinstance(k, int) else _php_export(k)) + " => "
        out += (_php_export(x, indent + "  ") if isinstance(x, (dict, list)) else _php_export(x)) + ",\n"
    return out + indent + ")"


def parse_users(lines):
    users, err = [], []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        p = [x.strip() for x in line.split(",")]
        name, role = p[0], (p[1] if len(p) > 1 else "editor").lower()
        if not valid_user_name(name) or role not in ("viewer", "editor", "admin"):
            err.append("Riga non valida: " + line)
            continue
        users.append((name, role))
    if not any(r == "admin" for _, r in users):
        err.append("Serve almeno una persona con ruolo admin.")
    return users, err


def new_token():
    return base64.b64encode(os.urandom(24)).decode("ascii").translate(str.maketrans("+/", "-_")).rstrip("=")


def run_setup(args) -> int:
    cfg_path = os.path.abspath(args.config)
    if os.path.exists(cfg_path):
        print("Configurazione già fatta: %s esiste già. Per ricominciare da capo spostala altrove "
              "(solo se il database è vuoto o se conservi la chiave)." % cfg_path, file=sys.stderr)
        return 3
    d = (args.data_dir or "").strip().rstrip("/\\")
    err = []
    if d == "" or not re.match(r"^(/|[A-Za-z]:[\\/])", d) or ".." in d:
        err.append('La cartella del database deve essere un percorso assoluto (senza "..").')
    if not err and os.path.exists(os.path.join(d, "docmap.sqlite")):
        # v12.4 rule (same as setup.php, HTTP 409 there): never pair an existing database with a new key
        print("Nella cartella %s c'è già un database (docmap.sqlite): una chiave nuova lo renderebbe illeggibile. "
              "Rimetti la configurazione originale (config.php / config.json con la sua chiave) oppure scegli "
              "una cartella vuota." % d, file=sys.stderr)
        return 4
    lines = []
    for u in args.user or []:
        lines.append(u)
    if args.users:
        lines.extend(re.split(r"\r\n|\r|\n|;", args.users))
    users, uerr = parse_users(lines)
    err += uerr
    if not err and not os.path.isdir(d):
        try:
            os.makedirs(d, 0o700, exist_ok=True)
        except OSError:
            err.append("Impossibile creare la cartella " + d + ".")
    if not err and not os.access(d, os.W_OK):
        err.append("La cartella " + d + " non è scrivibile.")
    if err:
        print("\n".join(err), file=sys.stderr)
        return 2
    for fname, content in ((".htaccess", "Require all denied\nOptions -Indexes\n"), ("index.html", "<!DOCTYPE html><title>403</title>\n")):
        fp = os.path.join(d, fname)
        if not os.path.isfile(fp):
            try:
                with open(fp, "w", encoding="utf-8", newline="\n") as f:
                    f.write(content)
            except OSError:
                pass
    tokens, shown = [], []
    for name, role in users:
        tok = new_token()
        tokens.append({"user": name, "role": role, "token_sha256": hashlib.sha256(tok.encode("ascii")).hexdigest()})
        shown.append((name, role, tok))
    cfg = {"data_dir": d, "aes_key": base64.b64encode(os.urandom(32)).decode("ascii"), "tokens": tokens,
           "allowed_origins": ["null"] if args.allow_file else [], "max_fails": 5, "lock_seconds": 60, "max_body_mb": 20,
           "studio_name": (args.studio_name or "").strip().encode("utf-8")[:120].decode("utf-8", "ignore")}
    fmt = args.format or ("php" if cfg_path.lower().endswith(".php") else "json")
    if fmt == "php":
        text = ("<?php\n/* DocMap 2026 — generated by setup.php on " + time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime()) +
                " UTC. KEEP A COPY IN A SAFE PLACE:\n   without aes_key the database (and its backups) cannot be read. Never publish or e-mail this file. */\n"
                "if (!defined('DOCMAP_API')) { http_response_code(404); exit; }\nreturn " + _php_export(cfg).lstrip("\n") + ";\n")
    else:
        text = json.dumps(cfg, ensure_ascii=False, indent=2) + "\n"
    os.makedirs(os.path.dirname(cfg_path) or ".", exist_ok=True)
    tmp = cfg_path + ".tmp-" + os.urandom(4).hex()
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    try:
        os.chmod(tmp, 0o600)
    except OSError:
        pass
    os.replace(tmp, cfg_path)
    print("Fatto: database online configurato.")
    print("Configurazione: %s  (CONSERVANE UNA COPIA AL SICURO: senza aes_key il database non si legge)" % cfg_path)
    print("Database: %s (creato al primo uso)\n" % os.path.join(d, "docmap.sqlite"))
    print("Copia adesso i codici di accesso: non verranno più mostrati.\n")
    w = max([len(n) for n, _, _ in shown] + [7])
    print("%-*s  %-6s  %s" % (w, "Persona", "Ruolo", "Codice di accesso (token)"))
    for n, r, t in shown:
        print("%-*s  %-6s  %s" % (w, n, r, t))
    return 0
